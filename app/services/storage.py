"""Where uploaded files live.

STORAGE_BACKEND:
  local (default) - UPLOAD_DIR on the server's disk. On Render's free plan this disk is wiped on every
                    redeploy, so use it only for development.
  s3              - any S3-compatible bucket: Cloudflare R2 (free tier), Supabase Storage, AWS S3, Backblaze B2.
                    Needs STORAGE_S3_BUCKET, STORAGE_S3_ACCESS_KEY, STORAGE_S3_SECRET_KEY, and for
                    non-AWS services STORAGE_S3_ENDPOINT (e.g. https://<account>.r2.cloudflarestorage.com).

Everything stored here is already encrypted by the caller (services.vault), so the bucket never holds
readable personal data.
"""
import os

from flask import current_app

_client = None


def _backend():
    return (current_app.config.get("STORAGE_BACKEND") or "local").lower()


def _s3():
    global _client
    if _client is None:
        import boto3  # imported lazily: only needed when the s3 backend is on
        cfg = current_app.config
        _client = boto3.client("s3", endpoint_url=cfg.get("STORAGE_S3_ENDPOINT") or None,
                               aws_access_key_id=cfg["STORAGE_S3_ACCESS_KEY"],
                               aws_secret_access_key=cfg["STORAGE_S3_SECRET_KEY"],
                               region_name=cfg.get("STORAGE_S3_REGION") or "auto")
    return _client


def _path(name):
    safe = os.path.basename(name)  # names are generated by us; never allow a path
    return os.path.join(current_app.config["UPLOAD_DIR"], safe)


def put(name, blob: bytes):
    if _backend() == "s3":
        _s3().put_object(Bucket=current_app.config["STORAGE_S3_BUCKET"], Key=os.path.basename(name), Body=blob)
        return
    os.makedirs(current_app.config["UPLOAD_DIR"], exist_ok=True)
    with open(_path(name), "wb") as f:
        f.write(blob)


def get(name):
    """The stored bytes, or None when the file is gone."""
    if _backend() == "s3":
        try:
            obj = _s3().get_object(Bucket=current_app.config["STORAGE_S3_BUCKET"], Key=os.path.basename(name))
            return obj["Body"].read()
        except Exception as exc:
            current_app.logger.warning("storage get %s failed: %s", name, exc)
            return None
    try:
        with open(_path(name), "rb") as f:
            return f.read()
    except OSError:
        return None


def delete(name):
    try:
        if _backend() == "s3":
            _s3().delete_object(Bucket=current_app.config["STORAGE_S3_BUCKET"], Key=os.path.basename(name))
        else:
            os.remove(_path(name))
    except Exception:
        pass


def status():
    cfg = current_app.config
    backend = _backend()
    if backend == "s3":
        missing = [k for k in ("STORAGE_S3_BUCKET", "STORAGE_S3_ACCESS_KEY", "STORAGE_S3_SECRET_KEY") if not cfg.get(k)]
        return {"backend": "s3", "durable": not missing, "missing": missing}
    return {"backend": "local", "durable": False, "missing": []}
